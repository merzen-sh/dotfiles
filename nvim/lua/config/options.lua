-- =============================================================================
-- OPTIONS
-- =============================================================================

local set = vim.opt

-- =============================================================================
-- Line Numbers
-- =============================================================================

set.number = true
set.relativenumber = true

-- =============================================================================
-- Indentation
-- =============================================================================

set.tabstop = 4
set.shiftwidth = 4
set.softtabstop = 4

set.expandtab = true
set.autoindent = true

-- =============================================================================
-- Search
-- =============================================================================

set.ignorecase = true
set.smartcase = true
set.incsearch = true

-- =============================================================================
-- Appearance
-- =============================================================================

set.cursorline = true

-- Hide "~" on empty lines
set.fillchars:append({
    eob = " ",
})

-- Always reserve space for diagnostics/signs
set.signcolumn = "yes"

vim.api.nvim_set_hl(0, "SignColumn", {
    bg = "none",
})

-- 80th column
set.colorcolumn = "80"

-- =============================================================================
-- Command Line
-- =============================================================================

set.cmdheight = 1

-- =============================================================================
-- Clipboard
-- =============================================================================

set.clipboard:append("unnamedplus")

-- =============================================================================
-- Editing
-- =============================================================================

set.backspace = {
    "indent",
    "eol",
    "start",
}

-- Treat "-" as part of a word
set.iskeyword:append("-")

-- =============================================================================
-- Windows
-- =============================================================================

set.splitbelow = true
set.splitright = true

-- =============================================================================
-- Scrolling
-- =============================================================================

set.scrolloff = 8
set.sidescrolloff = 8

-- =============================================================================
-- Performance
-- =============================================================================

set.updatetime = 100

-- =============================================================================
-- Files
-- =============================================================================

set.autoread = true

vim.api.nvim_create_autocmd({ "FocusGained", "BufEnter", "CursorHold" }, {
    callback = function()
        vim.cmd("checktime")
    end,
})
